export function generateBangaloreCSV(): string {
  const headers = [
    "Company Name",
    "Year Founded",
    "Location",
    "Last Funding Round",
    "Last Funding Amount (USD)",
    "Last Funding Date",
  ];
  const rows = bangaloreCompanies.map((c) => [
    c.company_name,
    c.year_founded,
    c.location,
    c.last_funding_round_type,
    String(c.last_funding_amount_usd),
    c.last_funding_date,
  ]);
  return [headers, ...rows]
    .map((row) => row.map((cell) => `"${cell.replace(/"/g, '""')}"`).join(","))
    .join("\n");
}
